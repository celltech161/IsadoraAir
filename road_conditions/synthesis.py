"""KanDrive audio synthesis and Track lifecycle.

Output-unit design (see report.py's module docstring for the length
reasoning that follows from it): KanDrive is ONE consolidated,
in-place-updated report -- a single stable file/Track, filepath-keyed,
regenerated in full on every successful cycle -- rather than one file
per event or a bounded set of "parts." This mirrors weather's own
WxForecast/WxObs/WxTemp family exactly (see the migration comment in
library/migrations/0076_add_kandrive_category.py): each of those is
also a single reused Track a human has manually wired into rotation,
regenerated by filepath-keyed update_or_create on its own schedule,
never accumulating. It deliberately does NOT follow the Dedications
family's pattern (one file per SongRequest id, urgent-splice-only,
zero RotationSlots) -- KanDrive IS meant to be rotation-eligible (the
operator adds it to rotations manually, per the task's own
instructions), so unlike a dedication intro it needs REAL crossfade
cue points, not the speech-clip opt-out next_start_seconds=duration
trick dedication intros use. That's why this module calls
analyze_one_track(force=True) and, unlike synthesize_dedication_intro,
never re-asserts next_start_seconds/cue_in_seconds afterward -- the
real envelope-based analysis is exactly what this Track needs to
crossfade correctly against whatever plays before/after it in a
rotation, the same as any other rotation category.

Rejected alternative -- one file per event: would multiply Track/file
count without bound as events churn, and the task explicitly prefers
"a small, predictable set of current KanDrive audio assets rather than
an ever-growing archive."

Rejected alternative -- bounded parts (e.g. Part 1/Part 2): would
require the rotation to play them in a specific order to remain
comprehensible, but RotationSlot.rotation_weight's own docstring
states selection is "not a guarantee" -- rotation is random-weighted,
not sequence-preserving. A multi-part report could play Part 2 without
Part 1 ever having aired, or hours apart, which would be actively
confusing rather than helpful. Not adopted.

Shared-TTS invocation mirrors the established in-Django pattern
(webrequests/services.py's synthesize_dedication_intro): the same
logical-voice API, WAV-then-ffmpeg-to-FLAC pipeline, and atomic
os.replace() (the final path is never touched until the new file is
completely written, probed and decoded cleanly), same temp-file naming
and cleanup. A failure before publication leaves the existing
final_path (and its Track row) completely untouched -- the last
known-good report keeps airing rather than going silent or corrupt. A
failure during publication restores it (see _publish_report()).

Ready-to-Air (1.24-B): this workflow sets ready2air=True when a newly
rendered, validated report has been published completely. It never
writes the flag otherwise -- not for failed or stale road data, a failed
render, an unchanged report, or the feature being disabled. Station
personnel keep the ordinary Library controls.

Three separate identities (1.24-B):
  * what the report says: report.compute_report_fingerprint(),
    voice-neutral, the only routine reason to render again;
  * how fresh the road data is: RoadConditionsConfiguration.
    last_fetch_*; stale or failed data stops new renders and notifies
    staff (alerts.py) while the last published report stays on air;
  * what is actually on disk: road_report.json beside the audio
    ("provenance") -- the rendered script, hashes, announcer, voice,
    engine, model and settings of the published recording. It is written
    last, so audio that no complete publication recorded never verifies.

Loudness normalization: the final spoken audio (whether one shared-TTS
call or several spliced with a transition sound -- see
_synthesize_with_transitions()) is run through the SAME two-pass EBU
R128 loudnorm target the KNS show ingest script applies to every other
syndicated show (get_kns.py's own LOUDNORM_TARGETS/build_loudnorm_
string/two-pass analyze-then-encode structure, duplicated here rather
than cross-imported). True
two-pass loudnorm structurally can't run as a single streaming pass
over a pipe -- the second pass's linear correction needs the first
pass's COMPLETE measurement before it can correctly apply anything
starting from sample 0 -- so this needs a real, re-readable file for
the provider's raw output (and, on the transition-sound path, each
segment's own WAV). Provider WAV writers may require a seekable path.
Given that and two-pass loudnorm, the closest thing to "no disk I/O
for this scratch
audio" is a tmpfs (RAM-backed, not real disk) directory -- see
TMP_AUDIO_ROOT below -- rather than true zero-file streaming, which
isn't possible here. The FINAL FLAC still lands on real disk at
KANDRIVE_ROOT, same as always; only the throwaway intermediate audio
moves to tmpfs, and every temp file (there or at KANDRIVE_ROOT) is
unlinked in synthesize_road_report()'s own `finally` block once the
final file has been written (or on failure) -- see that function.
"""
