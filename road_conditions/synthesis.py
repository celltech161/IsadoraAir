PROVENANCE_VERSION = 1
KANDRIVE_PROVENANCE_FILENAME = "road_report.json"
# Both exist only while a publication is incomplete: what to go back to,
# and the audio being replaced. Neither is an audio extension, so library
# scans ignore them.
KANDRIVE_PENDING_FILENAME = "road_report.publishing.json"
KANDRIVE_PREVIOUS_FILENAME = ".road_report.flac.previous"


def road_report_provenance_path():
    return KANDRIVE_ROOT / KANDRIVE_PROVENANCE_FILENAME


def road_report_pending_path():
    return KANDRIVE_ROOT / KANDRIVE_PENDING_FILENAME


def road_report_previous_path():
    return KANDRIVE_ROOT / KANDRIVE_PREVIOUS_FILENAME


def _write_json_atomically(path, payload):
    KANDRIVE_ROOT.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    try:
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2, sort_keys=True, allow_nan=False)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)


def _remove_quietly(path):
    try:
        path.unlink(missing_ok=True)
    except OSError as exc:
        logger.warning("road_conditions: could not remove %s: %s", path, exc)


def _sha256_or_none(path):
    try:
        return hash_file_sha256(path)
    except OSError:
        return None


def _sha256_text(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _read_text_or_none(path):
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeError):
        return None


def read_provenance():
    """(record, "") or (None, "provenance_missing" | "provenance_invalid")."""
    try:
        raw = road_report_provenance_path().read_text(encoding="utf-8")
    except FileNotFoundError:
        return None, "provenance_missing"
    except (OSError, UnicodeError):
        return None, "provenance_invalid"
    try:
        record = json.loads(raw)
        track_id = record["track"]["id"]
        valid = (
            record["provenance_version"] == PROVENANCE_VERSION
            and all(isinstance(record[key], str)
                    for key in ("semantic_fingerprint", "flac_sha256", "script", "script_sha256"))
            and isinstance(track_id, int) and not isinstance(track_id, bool)
        )
    except (ValueError, KeyError, TypeError):
        valid = False
    return (record, "") if valid else (None, "provenance_invalid")


def _published_track():
    return Track.objects.filter(filepath=str(_final_path())).first()


def published_report_problem(semantic_fingerprint):
    """"" only if the published audio, script, Track and provenance all
    verify AND describe `semantic_fingerprint`; otherwise why not.

    Verified against the publication's own provenance, never against a
    newly composed script, which names whichever announcer is scheduled
    now. Ready-to-Air plays no part: it belongs to the Library. Read-only."""
    if road_report_pending_path().exists():
        return "publication_incomplete"
    final_path = road_report_path()
    if not final_path.exists():
        return "flac_missing"
    provenance, problem = read_provenance()
    if provenance is None:
        return problem
    if _sha256_or_none(final_path) != provenance["flac_sha256"]:
        return "flac_mismatch"
    if not road_report_text_path().exists():
        return "text_missing"
    script = _read_text_or_none(road_report_text_path())
    if script is None or not (
        _sha256_text(script) == provenance["script_sha256"] == _sha256_text(provenance["script"])
    ):
        return "text_mismatch"
    track = _published_track()
    if track is None:
        return "track_missing"
    if track.id != provenance["track"]["id"]:
        return "track_mismatch"
    if not semantic_fingerprint or provenance["semantic_fingerprint"] != semantic_fingerprint:
        return "provenance_content_mismatch"
    return ""


def existing_report_is_healthy(semantic_fingerprint):
    """A matching stored fingerprint alone is never enough to skip a
    render. Repairs nothing."""
    return not published_report_problem(semantic_fingerprint)


def _waveform_witness(track):
    try:
        info = os.stat(track.waveform_path) if track.waveform_path else None
    except OSError:
        info = None
    return [info.st_ino, info.st_size, info.st_mtime_ns] if info else None


def _read_pending():
    try:
        record = json.loads(road_report_pending_path().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    keys = {"publication_id", "new_flac_sha256", "previous_flac_sha256", "previous_script",
            "previous_track"}
    return record if isinstance(record, dict) and keys <= record.keys() else None


def _begin_publication(candidate):
    """Records what to go back to, then replaces the audio; returns the new
    publication's id. If an earlier publication is still incomplete, its
    record of the last COMPLETE publication is kept rather than overwritten
    with a half-published one."""
    final_path = _final_path()
    previous = road_report_previous_path()
    record = _read_pending()
    if record is None or not (
        record["previous_flac_sha256"] is None
        or _sha256_or_none(previous) == record["previous_flac_sha256"]
    ):
        previous.unlink(missing_ok=True)
        previous_sha256 = None
        if final_path.exists():
            os.link(final_path, previous)
            previous_sha256 = hash_file_sha256(previous)
        track = _published_track()
        record = {
            "previous_flac_sha256": previous_sha256,
            "previous_script": _read_text_or_none(road_report_text_path()),
            "previous_track": None if track is None else {
                "id": track.id, "title": track.title, "duration_seconds": track.duration_seconds,
                "cue_marker_revision": track.cue_marker_revision, "waveform": _waveform_witness(track),
            },
        }
    # Names this attempt. Only a provenance record carrying it proves that
    # this publication committed: the audio hash cannot, because a
    # re-render can be byte-identical to what it replaces.
    record["publication_id"] = uuid.uuid4().hex
    record["new_flac_sha256"] = hash_file_sha256(candidate)
    record["started_at"] = dj_timezone.now().isoformat()
    _write_json_atomically(road_report_pending_path(), record)
    # Atomic -- no reader ever sees a partially-written final_path.
    os.replace(candidate, final_path)
    return record["publication_id"]


def _finish_publication():
    """The only place this workflow writes Ready-to-Air: after the
    provenance record has committed the publication. Safe to repeat."""
    Track.objects.filter(filepath=str(_final_path())).update(ready2air=True)
    road_report_pending_path().unlink(missing_ok=True)
    _remove_quietly(road_report_previous_path())


def recover_incomplete_publication():
    """Settles a publication that failed or was killed part-way, without
    rendering anything. Only call while holding the generator's command
    lock. Returns:

      ""             nothing was incomplete;
      "completed"    it had committed: finished (Ready-to-Air enabled);
      "restored"     the previous recording is back, with its script and
                     Track metadata (re-analyzed if analysis had changed
                     markers or waveform). Ready-to-Air is not touched;
      "discarded"    there was no previous recording: the unfinished
                     audio was removed;
      "abandoned"    the audio on disk is neither side of that
                     publication (something else wrote it, such as an
                     older release after a rollback): the stale record is
                     dropped and nothing is overwritten;
      "unrestorable" it could not be completed. The pending record stays,
                     so the report keeps failing the health check and is
                     rendered again."""
    if not road_report_pending_path().exists():
        _remove_quietly(road_report_previous_path())
        return ""
    record = _read_pending()
    if record is None:
        return "unrestorable"
    final_path = _final_path()
    current_sha256 = _sha256_or_none(final_path)
    provenance, _problem = read_provenance()
    if (provenance is not None
            and provenance.get("publication_id") == record["publication_id"]
            and current_sha256 == provenance["flac_sha256"]):
        _finish_publication()
        return "completed"

    previous_sha256 = record["previous_flac_sha256"]
    if current_sha256 not in (None, previous_sha256, record["new_flac_sha256"]):
        road_report_pending_path().unlink(missing_ok=True)
        _remove_quietly(road_report_previous_path())
        return "abandoned"
    if previous_sha256 is None:
        if current_sha256 == record["new_flac_sha256"]:
            final_path.unlink(missing_ok=True)
        if record["previous_script"] is None:
            _remove_quietly(road_report_text_path())
        elif _read_text_or_none(road_report_text_path()) != record["previous_script"]:
            write_road_report_text(record["previous_script"])
        before, row = record["previous_track"], _published_track()
        if before is not None and row is not None and row.id == before["id"]:
            _restore_track_columns(before, row)
        road_report_pending_path().unlink(missing_ok=True)
        return "discarded"

    if current_sha256 != previous_sha256:
        previous = road_report_previous_path()
        if _sha256_or_none(previous) != previous_sha256:
            return "unrestorable"
        # The kept copy stays until the whole restore has succeeded.
        restoring = KANDRIVE_ROOT / f".{KANDRIVE_FILENAME}.{os.getpid()}.restore"
        restoring.unlink(missing_ok=True)
        os.link(previous, restoring)
        os.replace(restoring, final_path)
    script = record["previous_script"]
    if script is not None and _read_text_or_none(road_report_text_path()) != script:
        write_road_report_text(script)
    if not _restore_track(record["previous_track"]):
        return "unrestorable"
    road_report_pending_path().unlink(missing_ok=True)
    _remove_quietly(road_report_previous_path())
    return "restored"


def _restore_track_columns(before, track):
    """The only two columns a publication changes that vary between reports."""
    if (track.title, track.duration_seconds) != (before["title"], before["duration_seconds"]):
        Track.objects.filter(pk=track.pk).update(
            title=before["title"], duration_seconds=before["duration_seconds"])


def _restore_track(before):
    """Puts back what a publication changes on the Track, and nothing else:
    never Ready-to-Air or any column it does not write. Cue markers and
    waveform are recomputed from the restored audio, through the ordinary
    analysis and cue-marker authority, only if they had changed."""
    track = _published_track()
    if before is None or track is None or track.id != before["id"]:
        return True
    _restore_track_columns(before, track)
    if (track.cue_marker_revision == before["cue_marker_revision"]
            and _waveform_witness(track) == before["waveform"]):
        return True
    try:
        track.refresh_from_db()
        analyzed = _run_full_analysis(track)
    except Exception as exc:  # noqa: BLE001 -- leaves "unrestorable"; the report is rendered again
        logger.warning("road_conditions: re-analysis of the restored report failed: %s", exc)
        return False
    if not analyzed:
        return False
    _finish_waveform(analyzed)
    return True


def _probe_duration(path):
    """Same ffprobe pattern as webrequests/services.py's own
    _probe_duration (itself matching prep_mitd_show.py's) -- duration
    in seconds as a float."""
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "default=nw=1:nk=1", str(path)],
        check=True, capture_output=True, text=True, timeout=15,
    )
    return float(out.stdout.strip())


def _validate_candidate(path, duration):
    """The finished candidate must have a real duration and decode cleanly
    from start to end before it may replace anything."""
    if not (math.isfinite(duration) and duration > 0):
        raise ValueError(f"rendered report has no usable duration ({duration!r})")
    identity = audio_identity.compute(path)
    decoded = identity["frames"] / identity["sample_rate"]
    if abs(decoded - duration) > max(1.0, duration * 0.02):
        raise ValueError(f"rendered report decodes to {decoded:.1f}s, expected {duration:.1f}s")


def build_loudnorm_string(extra_args=""):
    """Same construction as the KNS show ingest script's own
    build_loudnorm_string() (get_kns.py) -- duplicated here rather
    than cross-imported. Uses LOUDNORM_TARGETS, the same numbers KNS
    applies to every other syndicated show."""
    base = "loudnorm=I={I}:TP={TP}:LRA={LRA}".format(**LOUDNORM_TARGETS)
    return f"{base}:{extra_args}" if extra_args else base


def _parse_loudnorm_output(ffmpeg_output_text):
    """Same regex-based parse as get_kns.py's own
    _parse_loudnorm_output -- loudnorm's analysis pass prints its
    measurements as JSON to stderr (via av_log at AV_LOG_INFO); this
    pulls out the five fields the encode pass needs, falling back to a
    looser numeric regex if the quoted-JSON form isn't found (matches
    the original)."""
    keys = ["input_i", "input_tp", "input_lra", "input_thresh", "target_offset"]
    analysis = {}
    for k in keys:
        m = re.search(rf'"{k}"\s*:\s*"([^"]+)"', ffmpeg_output_text)
        if m:
            analysis[k] = m.group(1)
        else:
            lm = re.search(rf'{k}[^-\d]*([-\d.]+)', ffmpeg_output_text, re.I)
            if lm:
                analysis[k] = lm.group(1)
    return analysis


def _run_loudnorm_two_pass(build_filter_args, tmp_flac):
    """Two-pass EBU R128 loudnorm, matching the KNS show ingest
    script's own analyze-then-encode structure exactly (get_kns.py's
    merge_audio_files): pass 1 measures the COMPLETE finished audio
    (whatever filter graph `build_filter_args` produces, with loudnorm
    applied as `print_format=json`, discarded via `-f null -`); pass 2
    re-runs the SAME graph with `measured_*`/`linear=true`/
    `print_format=summary` and writes the real FLAC output. See this
    module's own docstring for why a single streaming pass can't do
    this (pass 2's linear correction needs pass 1's complete
    measurement before it can correctly apply anything from the very
    first sample).

    `build_filter_args(loudnorm_filter_str)` must return the full
    ffmpeg argv up to (but not including) the final output-format/path
    arguments -- called twice, once per pass, with a different
    loudnorm filter string each time, against the SAME already-
    synthesized input file(s) (no re-synthesis between passes).

    A failed/incomplete analysis pass (rare -- a very short or unusual
    clip) falls back to the same conservative defaults KNS itself uses
    (get_kns.py's own fallback) rather than failing the whole cycle
    over a measurement quirk -- matching KNS's own `check=False`
    treatment of its analysis pass. The ENCODE pass is not forgiving:
    its failure (CalledProcessError/TimeoutExpired) propagates
    normally to the caller's existing except clause, same as every
    other ffmpeg call in this module."""
    analyze_filter = build_loudnorm_string("print_format=json")
    try:
        proc1 = subprocess.run(
            build_filter_args(analyze_filter) + ["-f", "null", "-"],
            capture_output=True, text=True, timeout=60,
        )
        analysis = _parse_loudnorm_output((proc1.stdout or "") + (proc1.stderr or ""))
    except (subprocess.TimeoutExpired, OSError):
        analysis = {}

    if not analysis or len(analysis) < 5:
        analysis = dict(input_i="-20", input_tp="-2", input_lra="6", input_thresh="-30", target_offset="0")

    encode_filter = build_loudnorm_string(
        f"measured_I={analysis['input_i']}:measured_TP={analysis['input_tp']}:"
        f"measured_LRA={analysis['input_lra']}:measured_thresh={analysis['input_thresh']}:"
        f"offset={analysis['target_offset']}:linear=true:print_format=summary"
    )
    # Generous but bounded -- this is encoding already-synthesized
    # short WAVs, not a sized estimate.
    subprocess.run(
        build_filter_args(encode_filter) + [
            "-ar", "44100", "-ac", "2", "-c:a", "flac", "-sample_fmt", "s16",
            "-compression_level", "5", str(tmp_flac),
        ],
        check=True, timeout=120, capture_output=True,
    )


def _synthesize_segment_wav(voice, text, output_wav):
    """Applied identically to the plain single-call path
    (synthesize_road_report's own body) and every per-segment call in
    _synthesize_with_transitions() below. Routes through the shared
    isadoraair.tts.station.synthesize_station_voice() API, passing ONLY
    voice["logical_voice_name"] -- an operator-selected logical station
    voice name -- never voice["model"] (which holds the RESOLVED
    provider voice id, e.g. "af_jessica", kept only for report.
    compute_report_fingerprint()'s fingerprint authenticity; see
    voice.py's _resolve_shared_schedule_voice()). Timeout is
    voice["tts_timeout_seconds"] (RoadConditionsConfiguration.
    tts_timeout_seconds, applied per call -- i.e. per segment on the
    transition-sound path, matching that field's own documented
    intent).

    `voice` is always a road_conditions.voice.resolve_voice()-shaped
    dict -- that function raises VoiceResolutionError before returning
    anything else (the direct-Kokoro fallback this used to route to for
    a legacy/unshaped dict was retired in r0029; that runtime no longer
    exists).

    Raises isadoraair.tts.errors.TTSError, caught by
    synthesize_road_report()'s own wrapping try/except and turned into
    a SynthesisError, non-fatal and last-known-good-preserving."""
    synthesize_station_voice(
        text,
        voice=voice["logical_voice_name"],
        output_path=output_wav,
        timeout_seconds=voice["tts_timeout_seconds"],
    )


def _synthesize_with_transitions(segments, voice, transition_sound_path, tmp_flac, pid, cleanup_paths):
    """One logical shared-TTS call per entry in `segments` (written to TMP_AUDIO_ROOT,
    not KANDRIVE_ROOT -- see the module docstring), concatenated via
    two-pass loudnorm (_run_loudnorm_two_pass above) with
    `transition_sound_path` spliced in strictly BETWEEN consecutive
    segments -- never before the first or after the last. Mirrors the
    KNS show ingest script's own woosh-between-stories concat
    (get_kns.py's _build_merge_ffmpeg_args/_canonical_input_chain) and
    its two-pass loudnorm, applied to the whole concatenated program
    (not each item individually) exactly as KNS applies it to its own
    bumper+stories+wooshes together. Writes directly to `tmp_flac`.
    Returns the resulting duration in seconds.

    Every per-segment WAV this creates is appended to `cleanup_paths`
    (the caller's own `finally` unlinks them all, success or failure) --
    this function itself never cleans up, matching the rest of
    synthesize_road_report()'s established pattern of one shared
    cleanup list/block rather than each step managing its own.

    Raises SynthesisError on any shared-TTS/ffmpeg failure, same as the
    plain single-call path -- a bad transition-sound file (corrupt,
    wrong format) surfaces here as an ffmpeg failure, not silently
    skipped; only a MISSING file is treated as "feature not usable
    right now" (see generate_road_condition_audio.py's own check,
    which is what decides whether transition_sound_path is passed in
    as non-None at all)."""
    TMP_AUDIO_ROOT.mkdir(parents=True, exist_ok=True)
    segment_wavs = []
    for i, segment_text in enumerate(segments):
        seg_wav = TMP_AUDIO_ROOT / f".{KANDRIVE_FILENAME}.{pid}.seg{i}.tmp.wav"
        cleanup_paths.append(seg_wav)
        _synthesize_segment_wav(voice, segment_text, seg_wav)
        segment_wavs.append(seg_wav)

    def build_filter_args(loudnorm_filter_str):
        inputs, parts, concat_labels = [], [], []
        idx = 0
        for i, seg_wav in enumerate(segment_wavs):
            inputs.extend(["-i", str(seg_wav)])
            parts.append(f"[{idx}:a]aresample=44100,aformat=sample_fmts=s16:channel_layouts=stereo[s{i}]")
            concat_labels.append(f"[s{i}]")
            idx += 1
            if i < len(segment_wavs) - 1:
                inputs.extend(["-i", str(transition_sound_path)])
                parts.append(f"[{idx}:a]aresample=44100,aformat=sample_fmts=s16:channel_layouts=stereo[w{i}]")
                concat_labels.append(f"[w{i}]")
                idx += 1
        segment_count = len(concat_labels)
        parts.append(f"{''.join(concat_labels)}concat=n={segment_count}:v=0:a=1,{loudnorm_filter_str}[final]")
        filter_complex = ";".join(parts)
        return (
            ["ffmpeg", "-hide_banner", "-loglevel", "warning", "-y"]
            + inputs
            + ["-filter_complex", filter_complex, "-map", "[final]"]
        )

    _run_loudnorm_two_pass(build_filter_args, tmp_flac)
    return _probe_duration(tmp_flac)


def synthesize_road_report(text, voice_slot, voice, segments=None, transition_sound_path=None,
                           *, semantic_fingerprint="", superseded=None):
    """Renders `text` through the shared TTS service via
    _synthesize_segment_wav() below, using the already-resolved
    `voice` dict (see road_conditions/voice.py's resolve_voice(), which
    is the ONLY place a voice should be chosen; this function just
    plays whatever it's handed) -- converts to FLAC, and attaches it as
    the single KanDrive Track via filepath-keyed update_or_create.

    `segments` and `transition_sound_path` are both optional and both
    default to None -- every existing caller passing just (text,
    voice_slot, voice) is completely unaffected and still gets the
    exact single-shared-TTS-call behavior this function has always had.
    When BOTH are given, `segments` has 2+ entries, AND
    transition_sound_path is a real, existing file, this instead
    synthesizes each entry in `segments` as its own shared-TTS call and
    concatenates them via ffmpeg with the transition sound file spliced
    in strictly BETWEEN consecutive segments -- see
    _synthesize_with_transitions() below, which mirrors the KNS show
    ingest script's own woosh-between-stories concat (get_kns.py's
    _build_merge_ffmpeg_args). `text` itself is not used for synthesis
    in that case (only `segments` is actually sent to shared TTS) -- it
    still identifies what the caller considers the human-readable full
    script (used for road_report.txt; see that call site), which by
    construction (report.py's compose_report_segments(), sharing
    _resolve_framing() with compose_report_script()) is exactly
    " ".join(segments).

    Any single segment with fewer than 2 real entries can't have a
    transition inserted anywhere (there's no boundary), so it silently
    falls back to the plain single-call path using `text` -- this is
    what makes a 0- or 1-event report, or the feature being disabled,
    behave identically to before this parameter existed.

    Raises SynthesisError on any synthesis, validation or publication
    failure (temp files are cleaned up regardless). A synthesis or
    validation failure leaves the final path and any existing Track row
    completely untouched; for a publication failure see
    _publish_report(). Callers (the management command) decide how to log/report a
    SynthesisError; this function never silently swallows one, unlike
    synthesize_dedication_intro's own top-level catch-all -- KanDrive
    has no "next cycle will just retry automatically" scheduler of its
    own the way the dedication intro command's per-request loop does,
    so the command itself needs to see this failure to report it
    (Step 9's "individual event formatting failures... must not
    silently produce misleading audio" applies just as much to a
    synthesis-level failure).

    `superseded`, if given, is called once the candidate has been
    validated and before anything is replaced; a non-empty string raises
    ReportSuperseded with that reason.

    Publication (_publish_report()) covers the FLAC, the Track, waveform
    analysis, road_report.txt and the provenance record, which names
    `semantic_fingerprint` and is written last. Without a
    `semantic_fingerprint` the published report never verifies as
    current.

    Returns the Track instance on success, with ready2air=True."""

    use_transitions = bool(segments) and len(segments) > 1 and bool(transition_sound_path)

    KANDRIVE_ROOT.mkdir(parents=True, exist_ok=True)
    final_path = _final_path()
    pid = os.getpid()
    tmp_flac = KANDRIVE_ROOT / f".{KANDRIVE_FILENAME}.{pid}.tmp.flac"
    # Every temp file this call creates (the plain path's one tmp_wav,
    # or the transition path's per-segment WAVs) is appended here so
    # the single `finally` below cleans up either way, success or
    # failure -- same "always attempt, ignore FileNotFoundError"
    # pattern already established for tmp_flac itself.
    cleanup_paths = [tmp_flac]

    try:
        try:
            # Provenance only; an unusable sound file fails in ffmpeg.
            transition_sound_sha256 = _sha256_or_none(transition_sound_path) if use_transitions else None
            if use_transitions:
                duration = _synthesize_with_transitions(
                    segments, voice, transition_sound_path, tmp_flac, pid, cleanup_paths,
                )
            else:
                TMP_AUDIO_ROOT.mkdir(parents=True, exist_ok=True)
                tmp_wav = TMP_AUDIO_ROOT / f".{KANDRIVE_FILENAME}.{pid}.tmp.wav"
                cleanup_paths.append(tmp_wav)
                # Timeout is voice["tts_timeout_seconds"] -- see
                # _synthesize_segment_wav() -- NOT copied from
                # webrequests/services.py's 30s -- that value is sized
                # for a several-second dedication intro. A KanDrive
                # report is a full multi-event round-up (~780 words /
                # ~5-6 minutes of speech on the live dataset at
                # reconnaissance time), so a report this length could
                # reasonably take several minutes of wall time to
                # synthesize. RoadConditionsConfiguration.
                # tts_timeout_seconds' own default (600s) gives real
                # headroom above that without being unbounded -- a
                # genuinely hung synthesis process still gets killed,
                # just not mistaken for one on a long report.
                _synthesize_segment_wav(voice, text, tmp_wav)

                def build_filter_args(loudnorm_filter_str):
                    filter_str = f"aresample=44100,aformat=sample_fmts=s16:channel_layouts=stereo,{loudnorm_filter_str}"
                    return ["ffmpeg", "-hide_banner", "-loglevel", "warning", "-y", "-i", str(tmp_wav), "-af", filter_str]

                _run_loudnorm_two_pass(build_filter_args, tmp_flac)
                duration = _probe_duration(tmp_flac)
            _validate_candidate(tmp_flac, duration)
        except (subprocess.CalledProcessError, subprocess.TimeoutExpired, ValueError, TTSError,
                OSError, audio_identity.IdentityUnavailable) as exc:
            raise SynthesisError(f"Shared-TTS/ffmpeg synthesis failed: {exc}") from exc

        if superseded is not None:
            reason = superseded()
            if reason:
                raise ReportSuperseded(reason)

        rendering = {
            "audio_format_version": AUDIO_FORMAT_VERSION,
            "loudnorm": LOUDNORM_TARGETS,
            "sample_rate_hz": 44100, "channels": 2, "sample_format": "s16",
            "transition": {
                "active": use_transitions,
                "sound_sha256": transition_sound_sha256,
                "segment_count": len(segments) if use_transitions else None,
            },
        }
        return _publish_report(
            tmp_flac, text, voice_slot, voice, duration, semantic_fingerprint, rendering,
        )
    finally:
        for p in cleanup_paths:
            try:
                p.unlink()
            except FileNotFoundError:
                pass


def _publish_report(candidate, text, voice_slot, voice, duration, semantic_fingerprint, rendering):
    """Replaces the published report with the validated `candidate`.

    While it is incomplete a pending record says what to go back to, so a
    half-published report never verifies as healthy, even if the process
    is killed. In order: replace the FLAC, update the Track, run waveform
    analysis, write road_report.txt, write the provenance record (the
    commit point), then enable Ready-to-Air. A failure before the commit
    restores the previous recording (recover_incomplete_publication());
    one after it is completed by the next run.

    Ready-to-Air is not written before the commit: it is neither a lock
    nor part of recovery. No database transaction or row lock spans the
    decode or analysis: the engine updates this Track row from its main
    loop when the report starts to air, and must never wait behind them."""
    final_path = _final_path()
    try:
        flac_sha256 = hash_file_sha256(candidate)
        publication_id = _begin_publication(candidate)
    except BaseException as exc:
        _recover_after_failure(exc)
        if not isinstance(exc, Exception):
            raise
        raise SynthesisError(f"KanDrive publication could not start: {exc}") from exc

    try:
        # Only the columns a publication owns (update_or_create saves just
        # these), so anything else changed meanwhile is left alone.
        track, _created = Track.objects.update_or_create(
            filepath=str(final_path),
            defaults=dict(
                filename=final_path.name,
                format="flac",
                title=f"KanDrive Road Report ({voice['name']})",
                artist=_kandrive_artist(),
                duration_seconds=duration,
                category=_kandrive_category(),
            ),
        )
        # Full, real analysis -- unlike the Dedications intro pattern, this
        # Track IS meant to crossfade normally in rotation, so it needs
        # actual envelope-based cue points, not a speech-clip opt-out. A
        # report with no analysis would have no cue points for the log
        # builder, so a failed analysis fails the publication.
        analyzed = _run_full_analysis(track)
        if not analyzed:
            raise SynthesisError(f"waveform analysis of the new report (Track {track.id}) failed")
        _finish_waveform(analyzed)
        track.refresh_from_db()
        write_road_report_text(text)
        _write_json_atomically(road_report_provenance_path(), {
            "provenance_version": PROVENANCE_VERSION,
            "publication_id": publication_id,
            "semantic_fingerprint": semantic_fingerprint,
            "published_at": dj_timezone.now().isoformat(),
            "script": text,
            "script_sha256": _sha256_text(text),
            "flac_sha256": flac_sha256,
            "announcer": {
                "slot": voice_slot, "name": voice.get("name"), "full_name": voice.get("full_name"),
            },
            "voice": {
                "logical_voice_name": voice.get("logical_voice_name"),
                "engine": voice.get("engine"),
                "provider_voice": voice.get("model"),
                "language": voice.get("language"),
                "speed": voice.get("speed"),
            },
            "model": _model_identity(voice),
            "rendering": rendering,
            "track": {"id": track.id},
        })
    except BaseException as exc:
        outcome = _recover_after_failure(exc)
        if not isinstance(exc, Exception):
            raise
        raise SynthesisError(f"KanDrive publication failed ({outcome}): {exc}") from exc

    try:
        _finish_publication()
    except Exception as exc:
        raise SynthesisError(
            f"KanDrive report (Track {track.id}) was published but could not be finished; "
            f"the next run completes it: {exc}"
        ) from exc
    track.refresh_from_db()
    return track


def _recover_after_failure(cause):
    """Never replaces the original error."""
    try:
        outcome = recover_incomplete_publication()
    except Exception as exc:  # noqa: BLE001 -- the pending record remains for the next run
        logger.error("road_conditions: recovery after %r failed: %s", cause, exc)
        return "unrestorable"
    if outcome == "unrestorable":
        logger.error("road_conditions: could not restore the previous report after %r", cause)
    return {"": "nothing was replaced"}.get(outcome, f"previous report {outcome}")


def _model_identity(voice):
    """The pinned model of the engine that rendered, from the runtime
    component contract. Descriptive only: never blocks a publication."""
    if voice.get("engine") != "kokoro":
        return {"id": voice.get("model")}
    try:
        component = get_runtime_component("kokoro")
        return {
            "filename": component["assets"]["model"]["filename"],
            "contract_sha256": component["assets"]["model"]["sha256"],
            "kokoro_onnx": component["runtime"]["packages"]["kokoro-onnx"],
        }
    except Exception as exc:  # noqa: BLE001
        logger.warning("road_conditions: model identity unavailable: %s", exc)
        return {}


def _finish_waveform(analyzed):
    """Releases the waveform rollback copy once the analysis is kept."""
    promotion = getattr(analyzed, "promotion", None)
    if promotion is None:
        return
    try:
        promotion.discard()
    except Exception as exc:  # noqa: BLE001 -- the new waveform is in place either way
        logger.warning("road_conditions: could not finalize the report waveform: %s", exc)


def _run_full_analysis(track):
    from library.management.commands.analyze_tracks import analyze_one_track, get_waveforms_dir

    cfg = AnalysisConfig.load()
    cfg_values = (
        cfg.analysis_sample_rate, cfg.analysis_window_seconds, cfg.waveform_points,
        cfg.next_start_threshold_db, cfg.cue_in_threshold_db, cfg.cue_in_min_seconds,
    )
    if track.category_id:
        category = Category.objects.only(
            "next_start_threshold_db_override", "cue_in_threshold_db_override"
        ).get(pk=track.category_id)
        from library.management.commands.analyze_tracks import apply_category_thresholds
        cfg_values = apply_category_thresholds(
            cfg_values,
            category.next_start_threshold_db_override,
            category.cue_in_threshold_db_override,
        )
    row = (
        track.id, track.filepath, track.filename, track.duration_seconds,
        track.title, track.artist.name if track.artist_id else "", "",
    )
    # A freshly synthesized report replaced this Track's audio: its markers rebind to it.
    return analyze_one_track(row, cfg_values, get_waveforms_dir(), force=True, media_replaced=True,
                             keep_previous_waveform=True)


